"""Deterministically generate shared schema and UI contracts; no network use."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from .spec import SCHEMA_VERSION, SPECS


def json_schema() -> dict:
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "urn:compute-pricing:domain:1.0.0",
        "title": "Compute pricing domain contracts",
        "description": "Nullable intake fields preserve unknowns. Exact string decimals use x-decimal bounds enforced by the runtime parser. Permission and evidence fields are claims, not execution authority.",
        "x-schema-version": SCHEMA_VERSION,
        "$ref": "#/$defs/PricingRequest",
        "$defs": SPECS,
    }


def schema_text() -> str:
    return json.dumps(json_schema(), ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def _ts_type(spec: dict) -> str:
    if "$ref" in spec:
        return spec["$ref"].split("/")[-1]
    if "anyOf" in spec:
        return " | ".join(_ts_type(item) for item in spec["anyOf"])
    if "enum" in spec:
        return " | ".join("null" if value is None else json.dumps(value) for value in spec["enum"])
    kinds = spec.get("type")
    if isinstance(kinds, list):
        return " | ".join(_ts_type({**spec, "type": kind}) for kind in kinds)
    if kinds == "string":
        if spec.get("x-decimal"):
            return "DecimalString"
        if spec.get("format") == "date-time":
            return "UtcInstant"
        return "string"
    if kinds == "boolean":
        return "boolean"
    if kinds == "null":
        return "null"
    if kinds == "array":
        return f"ReadonlyArray<{_ts_type(spec['items'])}>"
    return "Readonly<Record<string, JsonValue>>"


def typescript_text() -> str:
    lines = [
        "// Generated by python -m compute_pricing.control.domain.generate. Edit the declarative spec.",
        "// Decimal strings preserve financial precision; UTC instants must end in Z.",
        "// Runtime parsers validate values. Permission claims never authorize trades.",
        f"export const DOMAIN_SCHEMA_VERSION = {json.dumps(SCHEMA_VERSION)} as const;",
        "export type DecimalString = string & { readonly __decimalString: unique symbol };",
        "export type UtcInstant = string & { readonly __utcInstant: unique symbol };",
        "export type JsonValue = null | boolean | number | string | ReadonlyArray<JsonValue> | { readonly [key: string]: JsonValue };",
        "",
    ]
    for name, spec in SPECS.items():
        lines.append(f"export interface {name} {{")
        for key, prop in spec["properties"].items():
            optional = "" if key in spec["required"] else "?"
            lines.append(f"  readonly {key}{optional}: {_ts_type(prop)};")
        lines.extend(("}", ""))
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[4])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        args.root / "docs/contracts/domain-v1.schema.json": schema_text(),
        args.root / "docs/contracts/domain-v1.types.txt": typescript_text(),
    }
    for path, expected in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f"Generated contract differs: {path.name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
